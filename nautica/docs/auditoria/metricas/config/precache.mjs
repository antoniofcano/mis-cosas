import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
const raiz = process.argv[2];
const self = {};
new Function('self', fs.readFileSync(path.join(raiz, 'sw-lista.js'), 'utf8'))(self);
const tam = (l) => l.reduce((a, p) => { const b = fs.readFileSync(path.join(raiz, p)); a.n++; a.b += b.length; a.gz += zlib.gzipSync(b).length; return a; }, { n: 0, b: 0, gz: 0 });
const mb = (x) => (x / 1048576).toFixed(2) + ' MB';
const A = tam(self.APP), D = tam(self.DATOS);
console.log('versión', self.VERSION);
console.log('APP  :', A.n, 'ficheros', mb(A.b), 'gzip', mb(A.gz));
console.log('DATOS:', D.n, 'ficheros', mb(D.b), 'gzip', mb(D.gz));
const js = self.APP.filter((p) => p.endsWith('.js'));
const J = tam(js);
console.log('  de ellos JS:', J.n, mb(J.b), 'gzip', mb(J.gz));
const css = tam(self.APP.filter((p) => p.endsWith('.css')));
console.log('  CSS:', css.n, mb(css.b), 'gzip', mb(css.gz));
const top = self.DATOS.map((p) => [fs.statSync(path.join(raiz, p)).size, p]).sort((a, b) => b[0] - a[0]).slice(0, 15);
console.log('== datos más grandes'); for (const [s, p] of top) console.log((s / 1024).toFixed(0).padStart(6), 'KB', p);
